const dictionaries: Record<Locale, Record<TranslationKey, string>> = { en, 'zh-CN': zh };

export function resolveLocale(stored: string | null | undefined, browserLanguages: readonly string[] = []): Locale {
  if (stored === 'en' || stored === 'zh-CN') return stored;
  return browserLanguages.some((language) => language.toLowerCase().startsWith('zh')) ? 'zh-CN' : 'en';
}

function translate(locale: Locale, key: TranslationKey, values?: Record<string, string | number>): string {
  const template = dictionaries[locale][key] ?? en[key];
  return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(values?.[name] ?? `{{${name}}}`));
}

type I18nContextValue = {
  locale: Locale;
  setLocale(locale: Locale): void;
  t(key: TranslationKey, values?: Record<string, string | number>): string;
};

const defaultValue: I18nContextValue = { locale: 'en', setLocale: () => {}, t: (key, values) => translate('en', key, values) };
const I18nContext = createContext<I18nContextValue>(defaultValue);

export function I18nProvider({ children, initialLocale }: { children: ReactNode; initialLocale?: Locale }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    if (initialLocale) return initialLocale;
    let stored: string | null = null;
    try { stored = globalThis.window?.localStorage.getItem(LOCALE_STORAGE_KEY); } catch { /* Ignore unavailable storage. */ }
    const languages = typeof navigator === 'undefined' ? [] : navigator.languages ?? [navigator.language];
    return resolveLocale(stored, languages);
  });
  useEffect(() => { if (typeof document !== 'undefined') document.documentElement.lang = locale; }, [locale]);
  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
    try { globalThis.window?.localStorage.setItem(LOCALE_STORAGE_KEY, next); } catch { /* Ignore unavailable storage. */ }
  }, []);
  const value = useMemo<I18nContextValue>(() => ({ locale, setLocale, t: (key, values) => translate(locale, key, values) }), [locale, setLocale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue { return useContext(I18nContext); }
